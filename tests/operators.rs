#[test]
fn operator_regressions() {
    for (source, expected) in CASES {
        let result = Interpreter::new()
            .eval(source)
            .unwrap_or_else(|e| panic!("{source}: {e}"));
        assert_eq!(result.to_string(), *expected, "{source}");
    }
}

#[test]
fn failed_amends_and_cyclic_dictionary_keys_preserve_destinations() {
    let mut interpreter = Interpreter::new();
    interpreter.eval("a:1 2;b:a;d:()!()").unwrap();
    for source in [
        "@[a;0 5;+;10 20]",
        "a[0 5]+:10 20",
        "a[0 0n]:10 20",
        "@[a;0 0n;:;10 20]",
        "d[{d}]:1",
    ] {
        assert!(interpreter.eval(source).is_err(), "{source}");
        assert_eq!(interpreter.eval("b").unwrap().to_string(), "1 2");
        assert_eq!(interpreter.eval("#d").unwrap().to_string(), "0");
    }
    interpreter.eval("a[0 0]+:10 20").unwrap();
    assert_eq!(interpreter.eval("b").unwrap().to_string(), "31 2");
}

#[test]
fn functional_amend_copies_but_assignment_preserves_shared_children() {
    let mut interpreter = Interpreter::new();
    interpreter
        .eval("row:1 2;m:(row;3 4);n:.[m;0 0;:;9]")
        .unwrap();
    assert_eq!(interpreter.eval("row").unwrap().to_string(), "1 2");
    assert_eq!(interpreter.eval("n[0]").unwrap().to_string(), "9 2");
    interpreter.eval("m[0][0]+:10").unwrap();
    assert_eq!(interpreter.eval("row").unwrap().to_string(), "11 2");
}

#[test]
fn roll_and_deal_obey_bounds_without_allocating_the_population() {
    for source in ["100?10", "-10?10", "2?1000000000000"] {
        let Value::Array(values) = Interpreter::new().eval(source).unwrap() else {
            panic!("{source}")
        };
        let numbers = values.as_numbers().unwrap();
        let bound = if source == "2?1000000000000" {
            1_000_000_000_000
        } else {
            10
        };
        for number in numbers.iter() {
            assert!(number.as_i64().unwrap() >= 0 && number.as_i64().unwrap() < bound);
            assert!(number.as_i64().is_some());
        }
        if source.starts_with('-') {
            let unique = numbers
                .iter()
                .map(|n| n.as_i64().unwrap())
                .collect::<std::collections::HashSet<_>>();
            assert_eq!(unique.len(), 10);
        }
    }
    for source in ["1?()", "-11?10", "2?0", "1.5?10"] {
        assert!(Interpreter::new().eval(source).is_err(), "{source}");
    }
}
